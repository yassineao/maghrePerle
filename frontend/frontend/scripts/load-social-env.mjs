import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const envPath = path.join(projectRoot, '.env');
const outputPath = path.join(
  projectRoot,
  'src/app/core/config/social-links.generated.ts',
);
const defaults = {
  WHATSAPP_NUMBER: '',
  INSTAGRAM_URL: 'https://www.instagram.com/maghrebella.boutique/',
};

function parseEnv(content) {
  const values = {};
  for (const line of content.split(/\r?\n/)) {
    const match = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/.exec(line);
    if (!match) continue;

    let value = match[2];
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    } else {
      value = value.replace(/\s+#.*$/, '').trim();
    }
    values[match[1]] = value;
  }
  return values;
}

let fileValues = {};
try {
  fileValues = parseEnv(await readFile(envPath, 'utf8'));
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

const config = Object.fromEntries(
  Object.entries(defaults).map(([key, fallback]) => [
    key === 'WHATSAPP_NUMBER' ? 'whatsappNumber' : 'instagramUrl',
    process.env[key] ?? fileValues[key] ?? fallback,
  ]),
);

await writeFile(
  outputPath,
  `// Generated by scripts/load-social-env.mjs. Do not edit.\nexport const socialLinksConfig = ${JSON.stringify(config, null, 2)};\n`,
);
